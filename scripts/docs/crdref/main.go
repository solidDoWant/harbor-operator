// Command crdref prints the CRD field reference (Markdown) for the CRD files
// in a directory. Every field becomes one table row with its path, type,
// whether it is required, and its description from the Go type comments.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"sigs.k8s.io/yaml"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: crdref <crd directory>")
		os.Exit(2)
	}

	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "crdref:", err)
		os.Exit(1)
	}
}

func run(directory string) error {
	files, err := filepath.Glob(filepath.Join(directory, "*.yaml"))
	if err != nil {
		return err
	}

	sort.Strings(files)

	var out strings.Builder

	out.WriteString("# Custom resource field reference\n\n")
	out.WriteString("For: chart authors who write harbor-operator resources.\n\n")
	out.WriteString("<!-- Generated by `make generate` from config/crd/bases. Do not edit. -->\n\n")
	out.WriteString("Every field of the `harbor.soliddowant.dev/v1alpha1` resources. A field marked `yes` in the Required column must be set. The page [write a project and a robot](example.md) shows them in use.\n")

	for _, file := range files {
		raw, err := os.ReadFile(file)
		if err != nil {
			return err
		}

		var crd apiextensionsv1.CustomResourceDefinition
		if err := yaml.Unmarshal(raw, &crd); err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}

		for _, version := range crd.Spec.Versions {
			fmt.Fprintf(&out, "\n## %s\n\n", crd.Spec.Names.Kind)
			out.WriteString("| Field | Type | Required | Description |\n|---|---|---|---|\n")

			for _, section := range []string{"spec", "status"} {
				writeFields(&out, section, version.Schema.OpenAPIV3Schema.Properties[section])
			}
		}
	}

	_, err = os.Stdout.WriteString(out.String())

	return err
}

func writeFields(out *strings.Builder, path string, schema apiextensionsv1.JSONSchemaProps) {
	required := map[string]bool{}
	for _, name := range schema.Required {
		required[name] = true
	}

	names := make([]string, 0, len(schema.Properties))
	for name := range schema.Properties {
		names = append(names, name)
	}

	sort.Strings(names)

	for _, name := range names {
		property := schema.Properties[name]
		full := path + "." + name

		requiredCell := ""
		if required[name] {
			requiredCell = "yes"
		}

		description := strings.Join(strings.Fields(property.Description), " ")
		description = strings.ReplaceAll(description, "|", "\\|")

		if len(property.Enum) > 0 {
			values := make([]string, 0, len(property.Enum))
			for _, value := range property.Enum {
				values = append(values, "`"+strings.Trim(string(value.Raw), `"`)+"`")
			}

			description += " One of " + strings.Join(values, ", ") + "."
		}

		fmt.Fprintf(out, "| `%s` | %s | %s | %s |\n", full, typeName(property), requiredCell, strings.TrimSpace(description))

		switch {
		case name == "selector":
			// A Kubernetes label selector: its fields are standard and noisy.
		case property.Type == "object" && len(property.Properties) > 0:
			writeFields(out, full, property)
		case property.Type == "array" && property.Items != nil && property.Items.Schema != nil && len(property.Items.Schema.Properties) > 0:
			writeFields(out, full+"[]", *property.Items.Schema)
		}
	}
}

func typeName(property apiextensionsv1.JSONSchemaProps) string {
	switch {
	case property.Type == "array" && property.Items != nil && property.Items.Schema != nil:
		return "list of " + typeName(*property.Items.Schema)
	case property.XIntOrString:
		return "quantity"
	case property.Type == "string" && property.Format == "date-time":
		return "time"
	case property.Type == "":
		return "any"
	}

	return property.Type
}
