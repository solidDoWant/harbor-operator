#!/usr/bin/env python3
"""Prints the chart values reference (Markdown) for a values.yaml.

A value is documented by a `# -- text` comment line right above it. Nested
keys are written with dots. Keys with no comment that only hold other keys are
skipped.
"""

import re
import sys

KEY = re.compile(r"^(\s*)([A-Za-z0-9_.-]+):(?:\s+(.*))?$")


def main(path):
    rows = []
    stack = []  # (indent, key)
    doc = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if line.lstrip().startswith("# --"):
                doc = line.lstrip()[4:].strip()
                continue
            match = KEY.match(line)
            if not match:
                continue
            indent, key, value = len(match.group(1)), match.group(2), match.group(3)
            while stack and stack[-1][0] >= indent:
                stack.pop()
            stack.append((indent, key))
            if doc is not None:
                name = ".".join(k for _, k in stack)
                rows.append((name, (value or "").strip(), doc))
                doc = None
    print("# Chart values")
    print()
    print("For: admins who install harbor-operator with its Helm chart.")
    print()
    print("<!-- Generated by `make generate` from deploy/charts/harbor-operator/values.yaml. Do not edit. -->")
    print()
    print("| Value | Default | Description |")
    print("|---|---|---|")
    for name, default, text in rows:
        shown = default if default != "" else '`""`'
        if default != "" and not default.startswith("`"):
            shown = f"`{default}`"
        print(f"| `{name}` | {shown} | {text} |")


if __name__ == "__main__":
    main(sys.argv[1])
